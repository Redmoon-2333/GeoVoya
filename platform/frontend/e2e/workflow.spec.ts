test('failed save preserves input and unsaved navigation can be cancelled', async ({ page }) => {
  await page.goto('/explore?node=sample-01')
  await page.locator('#observation-fact').fill('测试输入：连接失败后不能丢失。')
  await page.route('**/api/v1/observations/**', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: '测试连接中断，未保存。' }) }))
  await page.getByRole('button', { name: '保存观察', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('测试连接中断')
  await expect(page.locator('#observation-fact')).toHaveValue('测试输入：连接失败后不能丢失。')
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.locator('.node-strip button').nth(1).click()
  await expect(page.locator('#observation-fact')).toHaveValue('测试输入：连接失败后不能丢失。')
  await expect(page.locator('.photo-toolbar h2')).toHaveText('林下与地表')
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.getByRole('tab', { name: '数字沙盘', exact: true }).click()
  await expect(page.locator('#observation-fact')).toHaveValue('测试输入：连接失败后不能丢失。')
  await page.unroute('**/api/v1/observations/**')
  await page.getByRole('button', { name: '保存观察', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('观察记录已保存')
  await page.reload()
  await expect(page.locator('#observation-fact')).toHaveValue('测试输入：连接失败后不能丢失。')
})

test('six views render with real images and no horizontal overflow', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  const views = [['/', 'overview'], ['/explore', 'explore'], ['/inquiry', 'inquiry'], ['/archive', 'archive'], ['/outcomes', 'outcomes'], ['/feedback', 'feedback']]
  for (const [url, name] of views) {
    await page.goto(url!)
    await expect(page.locator('.main-content h1:visible')).toBeVisible()
    const images = page.locator('.main-content img:visible')
    for (const image of await images.all()) {
      await image.scrollIntoViewIfNeeded()
      await expect(image).toHaveJSProperty('complete', true)
      expect(await image.evaluate((element) => (element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
    }
    await page.evaluate(() => window.scrollTo(0, 0))
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    if (testInfo.project.name === 'mobile') {
      const launcher = await page.getByRole('button', { name: '打开小天课程提示', exact: true }).boundingBox()
      const header = await page.locator('.app-header').boundingBox()
      expect(launcher).toBeTruthy()
      expect(header).toBeTruthy()
      expect(launcher!.y).toBeGreaterThanOrEqual(header!.y)
      expect(launcher!.y + launcher!.height).toBeLessThanOrEqual(header!.y + header!.height)
    }
    await page.screenshot({ path: testInfo.outputPath(`${name}.png`), fullPage: true })
  }
  if (testInfo.project.name === 'mobile') {
    await page.getByRole('button', { name: '打开研学导航', exact: true }).click()
    await expect(page.locator('.study-sidebar')).toHaveClass(/open/)
    await page.locator('.journey-nav').getByRole('link', { name: /观察与记录/ }).click()
    await expect(page.locator('.study-sidebar')).not.toHaveClass(/open/)
    await page.getByRole('button', { name: '打开研学导航', exact: true }).click()
    await page.locator('.sidebar-next').click()
    await expect(page.locator('.study-sidebar')).not.toHaveClass(/open/)
  }
  expect(errors).toEqual([])
})
